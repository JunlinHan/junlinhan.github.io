"""Render data/publications.json into the publication tables of index.html.

Usage: python3 tools/build.py

Edit data/publications.json, then rerun this script and commit both files.
It rewrites only the region between the PUBS:START and PUBS:END markers in
index.html, so the page stays plain static HTML.

Each publication has: title, img (image path or .mp4), author (HTML; your
name in <b>), note (venue and year, e.g. "ICLR (oral), 2026"), link
([url, label] pairs) and highlight (true to list it under Selected Papers).
Papers are ordered by the year in note, newest first; papers from the same
year keep their order in the JSON file.
Optional image_size, image_crops (SVG viewBox rectangles), and media_alt
display a grid of original result panels without modifying the source image.
"""

from __future__ import annotations

import json
import re
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "publications.json"
PAGE = ROOT / "index.html"
START = "<!-- PUBS:START (generated by tools/build.py from data/publications.json) -->"
END = "<!-- PUBS:END -->"


def year(pub: dict) -> int:
    match = re.search(r"\d{4}", pub["note"])
    return int(match.group()) if match else 0


def row(pub: dict) -> str:
    if pub.get("image_crops"):
        # Display original result panels without altering the scientific images.
        width, height = pub["image_size"]
        panels = "".join(
            f'<svg viewBox="{" ".join(map(str, crop))}" aria-hidden="true" preserveAspectRatio="xMidYMid slice">'
            f'<image href="{escape(pub["img"], quote=True)}" width="{width}" height="{height}" /></svg>'
            for crop in pub["image_crops"]
        )
        media = f'<div class="pub-showcase" role="img" aria-label="{escape(pub["media_alt"], quote=True)}">{panels}</div>'
    elif pub["img"].endswith(".mp4"):
        media = f'<video autoplay loop muted playsinline><source src="{pub["img"]}" type="video/mp4"></video>'
    else:
        media = f'<img src="{pub["img"]}" alt="Teaser for {pub["title"]}" loading="lazy">'
    links = " ".join(f'<a href="{url}" target="_blank">[{label}]</a>' for url, label in pub["link"])
    title_class = "pub-title highlight" if pub["highlight"] else "pub-title"
    return f"""          <tr>
            <td class="pub-media"><div class="pub-thumb">{media}</div></td>
            <td>
              <p class="{title_class}">{pub["title"]}</p>
              <p class="pub-author">{pub["author"]}</p>
              <p class="pub-note">{pub["note"]}</p>
              <p class="pub-links">{links}</p>
            </td>
          </tr>"""


def table(table_id: str, pubs: list[dict]) -> str:
    rows = "\n".join(row(p) for p in pubs)
    return f'        <table class="pub-table" id="{table_id}">\n{rows}\n        </table>'


def render(pubs: list[dict]) -> str:
    selected = [p for p in pubs if p["highlight"]]
    return f"""      <div id="selected" class="pub-content active">
{table("selected-table", selected)}
      </div>

      <div id="all" class="pub-content">
{table("all-table", pubs)}
      </div>"""


def main() -> None:
    pubs = sorted(json.loads(DATA.read_text()), key=lambda p: -year(p))
    page = PAGE.read_text()
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pattern.search(page):
        raise SystemExit(f"PUBS markers not found in {PAGE}")
    block = f"{START}\n{render(pubs)}\n      {END}"
    PAGE.write_text(pattern.sub(lambda _: block, page))
    print(f"Rendered {len(pubs)} publications into {PAGE.name}")


if __name__ == "__main__":
    main()
